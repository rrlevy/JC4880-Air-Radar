const apt_t *airport_by_iata(const char *code)
{
    if (!code || !code[0]) return NULL;
    char key[4] = {0};
    for (int i = 0; i < 3 && code[i]; i++) {
        char c = code[i];
        if (c >= 'a' && c <= 'z') c = (char)(c - 32);
        key[i] = c;
    }
    int lo = 0;
    int hi = (int)(sizeof(s_airports) / sizeof(s_airports[0])) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        int cmp = strcmp(s_airports[mid].iata, key);
        if (cmp == 0) return &s_airports[mid];
        if (cmp < 0) lo = mid + 1;
        else hi = mid - 1;
    }
    return NULL;
}
